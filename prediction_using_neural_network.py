#neural network function


def loocv_multi_output_neural_network(data, feature_indices, target_indices, epochs=50, batch_size=8):
    """
    Builds, trains, and evaluates a neural network with multiple outputs using LOOCV.
    Returns the average MSE for each target variable on both training and test sets.

    Args:
        data: Pandas DataFrame containing the data.
        feature_indices: List of column indices for the features (X).
        target_indices: List of column names for the target variables (y1, y2, y3).
        epochs: Number of training epochs.
        batch_size: Batch size for training.

    Returns:
        A dictionary containing the average MSE for each target variable on both
        training and test sets across all LOOCV folds.
    """

    loo = LeaveOneOut()
    num_targets = len(target_indices)
    all_mse_train = [[] for _ in range(num_targets)]  # List of lists to store training MSE values
    all_mse_test = [[] for _ in range(num_targets)]  # List of lists to store test MSE values

    for train_index, test_index in loo.split(data):
        # Data Preparation:
        X_train = data.iloc[train_index][feature_indices]
        X_test = data.iloc[test_index][feature_indices]
        y_train = data.iloc[train_index][target_indices]
        y_test = data.iloc[test_index][target_indices]
        # Feature Scaling:
        '''
        scaler = StandardScaler()
        X_train = scaler.fit_transform(X_train)
        X_test = scaler.transform(X_test)
        '''
        # Model Definition:
        input_dim = len(feature_indices)
        model = keras.Sequential([
            layers.Input(shape=(input_dim,)),
            layers.Dense(64, activation='relu'),
            layers.Dense(32, activation='relu'),
            layers.Dense(num_targets)  # Output layer with num_targets neurons
        ])
        model.compile(loss='mse', optimizer='adam')

        # Training:
        model.fit(X_train, y_train, epochs=epochs, batch_size=batch_size, verbose=0)

        # Prediction and Evaluation:
        predictions_train = model.predict(X_train)  # Predictions on training set
        predictions_test = model.predict(X_test)  # Predictions on test set

        for i in range(num_targets):
            # Training MSE:
            y_pred_train = predictions_train[:, i] # Get all predictions for target i
            mse_train = mean_squared_error(y_train.iloc[:, i], y_pred_train)
            all_mse_train[i].append(mse_train)

            # Test MSE:
            # Reshape y_pred_test to be an array-like object with the same shape as y_test.iloc[:, i]
            y_pred_test = predictions_test[:, i].reshape(-1, 1) # Get the prediction for target i for the single test sample
            mse_test = mean_squared_error(y_test.iloc[:, i], y_pred_test)
            all_mse_test[i].append(mse_test)
    # Calculate average MSEs:
    # Use target_indices directly as keys, as they are already column names
    avg_mse_train = {target_indices[i]: np.mean(all_mse_train[i]) for i in range(num_targets)}
    avg_mse_test = {target_indices[i]: np.mean(all_mse_test[i]) for i in range(num_targets)}

    return {'train_mse': avg_mse_train, 'test_mse': avg_mse_test}

